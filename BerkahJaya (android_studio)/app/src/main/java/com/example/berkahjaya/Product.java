package com.example.berkahjaya;

public class Product {
    private int id;
    private String nama_produk;
    private double harga;
    private int stok;
    private String gambar;

    public int getId() {
        return id;
    }

    public String getNama_produk() {
        return nama_produk;
    }

    public double getHarga() {
        return harga;
    }

    public int getStok() {
        return stok;
    }

    public String getGambar() {
        return gambar;
    }
}